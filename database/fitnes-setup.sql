-- Скрипт настройки существующей базы fitnes для проекта FitnessEf.
-- Выполняется в pgAdmin4 через Query Tool от имени postgres.
-- Пароль и строка подключения в этот файл не записываются.

BEGIN;

-- Поле необязательно, поэтому добавление не требует изменения существующих строк.
ALTER TABLE public.clients
    ADD COLUMN IF NOT EXISTS note varchar(500);

-- Один клиент может иметь много посещений.
-- RESTRICT запрещает удалить клиента, пока у него есть посещения.
CREATE TABLE IF NOT EXISTS public.visits
(
    visit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id integer NOT NULL,
    visit_date date NOT NULL,
    note varchar(500),
    CONSTRAINT visits_client_id_fkey
        FOREIGN KEY (client_id)
        REFERENCES public.clients (client_id)
        ON DELETE RESTRICT
);

COMMIT;

-- Контроль результата после выполнения скрипта.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('clients', 'visits')
ORDER BY table_name;
